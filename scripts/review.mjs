// Dev helper: walks every section with an evolved experiment loaded and takes screenshots.
import { chromium } from '@playwright/test'
const dir = process.argv[2]
const base = process.env.URL ?? 'http://localhost:5240/?debug'
const opts = process.argv.slice(3)
const dark = opts.includes('--dark')
const mobile = opts.includes('--mobile')
const browser = await chromium.launch({ channel: 'chromium' })
const page = await browser.newPage({ viewport: mobile ? { width: 390, height: 780 } : { width: 1440, height: 880 }, colorScheme: dark ? 'dark' : 'light', hasTouch: mobile })
const suffix = dark ? '-dark' : mobile ? '-mobile' : ''
page.on('pageerror', (e) => console.log('PAGEERROR', e.message))
page.on('console', (m) => { if (m.type() === 'error') console.log('CONSOLE', m.text().slice(0, 240)) })
const shot = async (name, wait = 900) => { await page.waitForTimeout(wait); await page.screenshot({ path: `${dir}/${name}${suffix}.png` }) }
await page.goto(base)
await shot('1-intro', 2200)
await page.getByTestId('start-evolution').click()
await shot('2-watch', 5000)
await page.evaluate(() => window.__evolve.useSim.getState().setMode('fast'))
await page.waitForFunction(() => window.__evolve.useSim.getState().session?.history.length >= 25, null, { timeout: 120000 })
await page.evaluate(() => { const s = window.__evolve.useSim.getState(); s.setMode('watch'); s.stopEvolution() })
await page.waitForTimeout(1500)
await page.evaluate(() => window.__evolve.useSim.getState().backToLive())
await shot('3-evolved', 2500)
await page.goto(`${base}#/evolve`, { waitUntil: 'commit' }).catch(() => {})
await page.evaluate(() => { location.hash = '#/evolve' })
await shot('4-evolve', 2500)
await page.evaluate(() => document.querySelector('.page').scrollTo(0, 720))
await shot('4b-evolve-charts', 800)
await page.evaluate(() => document.querySelector('[data-testid="history-table"]').scrollIntoView())
await shot('4c-evolve-history', 1500)
await page.evaluate(() => document.querySelector('[data-testid="compare-stage"]').scrollIntoView({ block: 'center' }))
await shot('4d-compare', 1500)
await page.evaluate(() => { location.hash = '#/create' })
await shot('5-create', 1500)
await page.getByTestId('test-run').click()
await shot('5b-create-test', 2500)
await page.evaluate(() => { location.hash = '#/compete' })
await shot('6-compete', 1500)
await page.getByTestId('racer-preset:strider').click()
await page.getByTestId('racer-preset:trestle').click()
await page.getByTestId('racer-preset:pogo').click()
await page.getByTestId('racer-live-latest').click()
await page.getByTestId('start-race').click()
await shot('6b-race', 5200)
await page.evaluate(() => { location.hash = '#/experiments' })
await shot('7-experiments', 1200)
await page.getByTestId('lab-run').click()
await page.waitForFunction(() => document.querySelector('[data-testid="lab-summary"]'), null, { timeout: 180000 })
await page.evaluate(() => document.querySelector('[data-testid="lab-summary"]').scrollIntoView({ block: 'start' }))
await shot('7b-experiment-results', 1500)
await page.evaluate(() => { location.hash = '#/gallery' })
await shot('8-gallery', 1500)
await page.evaluate(() => { location.hash = '#/settings' })
await shot('9-settings', 900)
await browser.close()
